import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const outPath = path.join(rootDir, "android", "admob.local.properties");

async function fetchFromServer() {
  const baseUrl = (process.env.BASE_URL || "https://ppamong.com").replace(/\/$/, "");
  try {
    const res = await fetch(`${baseUrl}/api/config/admob`);
    if (!res.ok) return null;
    return await res.json();
  } catch (error) {
    console.warn(`[admob:write-native] 서버 설정 불러오기 실패 (${baseUrl}):`, error.message);
    return null;
  }
}

const serverConfig = await fetchFromServer();

const androidAppId =
  serverConfig?.androidAppId?.trim() ||
  process.env.ADMOB_APP_ID_ANDROID?.trim() ||
  process.env.VITE_ADMOB_APP_ID_ANDROID?.trim() ||
  "";

const iosAppId =
  serverConfig?.iosAppId?.trim() ||
  process.env.ADMOB_APP_ID_IOS?.trim() ||
  process.env.VITE_ADMOB_APP_ID_IOS?.trim() ||
  "";

if (!androidAppId && !iosAppId) {
  console.error("Android/iOS App ID를 찾을 수 없습니다.");
  console.error("");
  console.error("1) 관리자 → 동영상 광고 수익 현황 → AdMob Android 앱 적용");
  console.error("2) 서버 배포 후 이 PC에서 다시 실행: npm run admob:write-native");
  console.error("   (또는 .env 에 ADMOB_APP_ID_ANDROID=ca-app-pub-xxx~yyy 직접 설정)");
  process.exit(1);
}

const lines = [
  "# Generated by npm run admob:write-native — do not commit",
  androidAppId ? `ADMOB_APP_ID_ANDROID=${androidAppId}` : "# ADMOB_APP_ID_ANDROID=",
  iosAppId ? `ADMOB_APP_ID_IOS=${iosAppId}` : "# ADMOB_APP_ID_IOS=",
  "",
];

fs.writeFileSync(outPath, lines.join("\n"), "utf8");

console.log(`Written: ${outPath}`);
if (serverConfig?.androidAppId || serverConfig?.iosAppId) {
  console.log("  (ppamong.com 서버 설정에서 가져옴)");
}
if (androidAppId) {
  console.log(`  ADMOB_APP_ID_ANDROID=${androidAppId}`);
}
if (iosAppId) {
  console.log(`  ADMOB_APP_ID_IOS=${iosAppId}`);
}
console.log("");
console.log("다음: Android Studio 또는 ./gradlew assembleRelease 로 APK/AAB를 다시 빌드하세요.");
